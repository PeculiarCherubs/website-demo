import { loadCmsProfile } from "./rbac.js";
import { json, requestId, safeErrorResponse } from "./http.js";
import {
  loadCmsSections,
  validateSectionKeys,
  writeCmsSection,
  writeScopedChapel,
  writeScopedBroadcast,
  upsertScopedSermon,
  deleteScopedSermon,
  listHistory
} from "./adminContent.js";
import {
  listRoles,
  listAdmins,
  inviteAdmin,
  setAdminRole,
  setAdminScopes,
  removeAdmin
} from "./adminAccess.js";

async function assertDatabaseReady(env) {
  const rows = await env.DB.prepare(`
    SELECT key, value
    FROM schema_meta
    WHERE key IN (
      'application_schema',
      'worship_location_model',
      'public_content_contract',
      'cms_write_api'
    )
  `).all();

  const values = Object.fromEntries(
    (rows.results || []).map(row => [row.key, row.value])
  );

  if (values.application_schema !== "cloudflare-stage-2-v1") {
    const err = new Error("d1_stage2_schema_missing");
    err.code = "d1_stage2_schema_missing";
    err.status = 503;
    throw err;
  }

  if (values.worship_location_model !== "peculiar-hq-v1") {
    const err = new Error("d1_worship_location_model_missing");
    err.code = "d1_worship_location_model_missing";
    err.status = 503;
    throw err;
  }

  if (values.public_content_contract !== "cloudflare-stage-4-v1") {
    const err = new Error("d1_public_contract_missing");
    err.code = "d1_public_contract_missing";
    err.status = 503;
    throw err;
  }

  if (values.cms_write_api !== "cloudflare-stage-5-v1") {
    const err = new Error("d1_stage5_write_api_missing");
    err.code = "d1_stage5_write_api_missing";
    err.status = 503;
    throw err;
  }

  return values;
}

async function parseJsonBody(request) {
  const type = request.headers.get("content-type") || "";
  if (!type.includes("application/json")) {
    const err = new Error("json_body_required");
    err.code = "json_body_required";
    err.status = 415;
    throw err;
  }

  try {
    return await request.json();
  } catch (_) {
    const err = new Error("invalid_json_body");
    err.code = "invalid_json_body";
    err.status = 400;
    throw err;
  }
}

function adminRuntimeConfig() {
  return `/**
 * Generated by the Peculiar Cherubs Admin Worker.
 */
(function (global) {
  "use strict";
  global.PeculiarAdminRuntimeConfig = Object.freeze({
    provider: "cloudflare",
    apiBase: "/api/cms"
  });
})(typeof window !== "undefined" ? window : globalThis);
`;
}

export default {
  async fetch(request, env, ctx) {
    const id = requestId(request);
    const url = new URL(request.url);

    try {
      const identity = await requireAccessIdentity(request, ctx, env);
      await assertDatabaseReady(env);

      if (url.pathname === "/js/data/adminRuntimeConfig.js") {
        return new Response(adminRuntimeConfig(), {
          status: 200,
          headers: {
            "Content-Type": "application/javascript; charset=utf-8",
            "Cache-Control": "no-store",
            "X-Content-Type-Options": "nosniff"
          }
        });
      }

      if (url.pathname === "/api/identity" && request.method === "GET") {
        return json({
          ok: true,
          identity: {
            subject: identity.subject,
            email: identity.email,
            name: identity.name,
            aud: identity.aud
          },
          environment: env.ENVIRONMENT || "staging",
          request_id: id
        });
      }

      if (url.pathname === "/api/me" && request.method === "GET") {
        const profile = await loadCmsProfile(env, identity);
        return json({
          ok: true,
          profile,
          environment: env.ENVIRONMENT || "staging",
          request_id: id
        });
      }

      if (url.pathname === "/__health" && request.method === "GET") {
        return json({
          ok: true,
          service: "peculiar-cherubs-admin",
          stage: "cloudflare-stage-5",
          access_validated: true,
          database_ready: true,
          cms_ui_enabled: true,
          cms_write_api: true,
          request_id: id
        });
      }

      if (url.pathname === "/api/cms/sections" && request.method === "GET") {
        const profile = await loadCmsProfile(env, identity);
        const keys = validateSectionKeys(url.searchParams.get("keys"));
        const sections = await loadCmsSections(env, keys);
        return json({
          ok: true,
          sections,
          profile: {
            role_key: profile.role_key,
            scope_type: profile.scope_type,
            chapel_scopes: profile.chapel_scopes
          },
          request_id: id
        });
      }

      const sectionMatch = url.pathname.match(/^\/api\/cms\/sections\/([^/]+)$/);
      if (sectionMatch && request.method === "PUT") {
        const profile = await loadCmsProfile(env, identity);
        const key = decodeURIComponent(sectionMatch[1]);
        const body = await parseJsonBody(request);
        const saved = await writeCmsSection(
          env,
          profile,
          identity,
          key,
          body
        );
        return json({ ok: true, section: saved, request_id: id });
      }

      const chapelMatch = url.pathname.match(/^\/api\/cms\/chapels\/([^/]+)$/);
      if (chapelMatch && request.method === "PUT") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const saved = await writeScopedChapel(
          env,
          profile,
          identity,
          decodeURIComponent(chapelMatch[1]),
          body
        );
        return json({ ok: true, section: saved, request_id: id });
      }

      const broadcastMatch = url.pathname.match(/^\/api\/cms\/broadcasts\/([^/]+)$/);
      if (broadcastMatch && request.method === "PUT") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const saved = await writeScopedBroadcast(
          env,
          profile,
          identity,
          decodeURIComponent(broadcastMatch[1]),
          body
        );
        return json({ ok: true, section: saved, request_id: id });
      }

      const sermonMatch = url.pathname.match(/^\/api\/cms\/sermons\/([^/]+)$/);
      if (sermonMatch && request.method === "PUT") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const saved = await upsertScopedSermon(
          env,
          profile,
          identity,
          decodeURIComponent(sermonMatch[1]),
          body
        );
        return json({ ok: true, section: saved, request_id: id });
      }

      if (sermonMatch && request.method === "DELETE") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const saved = await deleteScopedSermon(
          env,
          profile,
          identity,
          decodeURIComponent(sermonMatch[1]),
          body
        );
        return json({ ok: true, section: saved, request_id: id });
      }

      if (url.pathname === "/api/cms/history" && request.method === "GET") {
        const profile = await loadCmsProfile(env, identity);
        const rows = await listHistory(
          env,
          profile,
          url.searchParams.get("limit")
        );
        return json({ ok: true, history: rows, request_id: id });
      }

      if (url.pathname === "/api/cms/roles" && request.method === "GET") {
        const profile = await loadCmsProfile(env, identity);
        return json({
          ok: true,
          roles: await listRoles(env, profile),
          request_id: id
        });
      }

      if (url.pathname === "/api/cms/admins" && request.method === "GET") {
        const profile = await loadCmsProfile(env, identity);
        return json({
          ok: true,
          admins: await listAdmins(env, profile),
          request_id: id
        });
      }

      if (url.pathname === "/api/cms/admins/invite" && request.method === "POST") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const result = await inviteAdmin(env, profile, identity, body);
        return json({ ...result, request_id: id }, 201);
      }

      const adminRoleMatch = url.pathname.match(/^\/api\/cms\/admins\/(.+)\/role$/);
      if (adminRoleMatch && request.method === "PATCH") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const result = await setAdminRole(
          env,
          profile,
          decodeURIComponent(adminRoleMatch[1]),
          body
        );
        return json({ ...result, request_id: id });
      }

      const adminScopeMatch = url.pathname.match(/^\/api\/cms\/admins\/(.+)\/scopes$/);
      if (adminScopeMatch && request.method === "PATCH") {
        const profile = await loadCmsProfile(env, identity);
        const body = await parseJsonBody(request);
        const result = await setAdminScopes(
          env,
          profile,
          decodeURIComponent(adminScopeMatch[1]),
          body
        );
        return json({ ...result, request_id: id });
      }

      const adminDeleteMatch = url.pathname.match(/^\/api\/cms\/admins\/(.+)$/);
      if (adminDeleteMatch && request.method === "DELETE") {
        const profile = await loadCmsProfile(env, identity);
        const result = await removeAdmin(
          env,
          profile,
          identity,
          decodeURIComponent(adminDeleteMatch[1])
        );
        return json({ ...result, request_id: id });
      }

      if (url.pathname.startsWith("/api/")) {
        return json({ ok: false, error: "not_found", request_id: id }, 404);
      }

      // Access-protected Admin asset shell.
      if (url.pathname === "/" || url.pathname === "/admin") {
        return Response.redirect(new URL("/admin/", request.url), 302);
      }

      if (url.pathname === "/admin/") {
        // Let Cloudflare Static Assets resolve /admin/ to /admin/index.html.
        // Fetching /admin/index.html directly triggers the default
        // auto-trailing-slash canonical redirect back to /admin/, which
        // creates a redirect loop.
        return env.ASSETS.fetch(request);
      }

      return env.ASSETS.fetch(request);

    } catch (error) {
      return safeErrorResponse(error, id);
    }
  }
};
